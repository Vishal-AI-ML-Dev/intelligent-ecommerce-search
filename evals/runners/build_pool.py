ALLOWED_ROOT = freeze_queries.ALLOWED_ROOT
DEFAULT_GOLDEN_DIR = freeze_queries.DEFAULT_GOLDEN_DIR
PRIVATE_ROOT = ROOT / "data" / "processed" / "golden_pool"
QUERIES_MANIFEST_PATH = freeze_queries.MANIFEST_PATH
POOL_MANIFEST_PATH = "manifests/2-pool_frozen.json"
POOL_PATHS: dict[Role, str] = {
    Role.POOL: "pool.jsonl",
    Role.ELIGIBILITY: "eligibility.jsonl",
    Role.POOL_REPORT: "pool_report.json",
}
PROVENANCE_FILE = "provenance.json"
# The four deterministic outputs of one run, compared byte for byte between runs.
RUN_FILES: tuple[str, ...] = (*sorted(POOL_PATHS.values()), PROVENANCE_FILE)


class PoolError(FreezeError):
    """The pool cannot be generated, frozen or verified."""


class DeterminismError(PoolError):
    """Two independent runs produced different bytes; nothing was frozen."""


@dataclass(frozen=True)
class FrozenQueries:
    manifest: Manifest
    queries: list[QueryRecord]
    constraints: list[GoldConstraint]


def load_frozen_queries(
    golden_dir: Path, *, allowed_root: Path = ALLOWED_ROOT, catalog: CatalogIndex
) -> FrozenQueries:
    """The verified `queries_frozen` stage (every hash, validator and regeneration checked)."""
    manifest = freeze_queries.verify(golden_dir, allowed_root=allowed_root, catalog=catalog)
    golden_dir = freeze_queries.safe_golden_dir(golden_dir, allowed_root)
    queries = decode_jsonl(read_frozen(golden_dir, "queries.jsonl"), QueryRecord)
    constraints = decode_jsonl(read_frozen(golden_dir, "gold_constraints.jsonl"), GoldConstraint)
    return FrozenQueries(manifest, queries, constraints)


# ---- run outputs ----------------------------------------------------------------------------


def run_files(build: PoolBuild) -> dict[str, bytes]:
    return {
        POOL_PATHS[Role.POOL]: build.pool_bytes(),
        POOL_PATHS[Role.ELIGIBILITY]: build.eligibility_bytes(),
        POOL_PATHS[Role.POOL_REPORT]: build.report_bytes(),
        PROVENANCE_FILE: build.provenance_bytes(),
    }


def compare_runs(first: Mapping[str, bytes], second: Mapping[str, bytes]) -> None:
    """Byte identity of every run file; the first difference names the file and line only."""
    for name in RUN_FILES:
        a, b = first.get(name), second.get(name)
        if a is None or b is None:
            raise DeterminismError(f"{name}: missing from a run")
        if a != b:
            lines_a, lines_b = a.split(b"\n"), b.split(b"\n")
            line = next(
                (i for i, (x, y) in enumerate(zip(lines_a, lines_b, strict=False), 1) if x != y),
                min(len(lines_a), len(lines_b)) + 1,
            )
            offset = next(
                (i for i, (x, y) in enumerate(zip(a, b, strict=False)) if x != y),
                min(len(a), len(b)),
            )
            raise DeterminismError(
                f"runs differ; nothing frozen. First difference: {name} line {line} "
                f"(byte offset {offset}; sizes {len(a)} vs {len(b)})"
            )


def decode_run(files: Mapping[str, bytes]) -> PoolBuild:
    try:
        return PoolBuild(
            pool=tuple(decode_jsonl(files[POOL_PATHS[Role.POOL]], PoolItem)),
            eligibility=tuple(decode_jsonl(files[POOL_PATHS[Role.ELIGIBILITY]], EligibilityRecord)),
            provenance=decode_json_object(files[PROVENANCE_FILE], PoolProvenance),
            report=decode_json_object(files[POOL_PATHS[Role.POOL_REPORT]], PoolReport),
        )
    except KeyError as exc:
        raise PoolError(f"a run output is missing: {exc}") from None


def check_build(
    frozen: FrozenQueries, catalog: CatalogIndex, files: Mapping[str, bytes]
) -> PoolBuild:
    """Everything a pool must satisfy before it is frozen (or after, when verifying):
    canonical bytes, the run context, the cap, every pool/provenance/eligibility validator, and
    an offline re-assembly from the provenance that reproduces every byte."""
    build = decode_run(files)
    context = build.provenance.run_context
    if context.queries_manifest_sha256 != frozen.manifest.manifest_sha256:
        raise PoolError("the provenance was generated from another queries_frozen manifest")
    if (context.dataset_id, context.dataset_version, context.dataset_checksum_sha256) != (
        catalog.dataset_id,
        catalog.dataset_version,
        catalog.checksum_sha256,
    ):
        raise PoolError("the provenance names another catalog dataset")
    check_pool_cap(build.pool, build.provenance.entries)
    validate_pool(frozen.queries, build.pool, catalog)
    validate_provenance(build.pool, build.provenance.entries, frozen.constraints, catalog)
    validate_eligibility(build.pool, frozen.constraints, build.eligibility)
    regenerated = [
        evaluate(item.query_id, frozen.constraints, catalog.products[item.product_id])
        for item in build.pool
    ]
    if encode_jsonl(regenerated) != files[POOL_PATHS[Role.ELIGIBILITY]]:
        raise PoolError("eligibility does not match its regeneration")
    rebuilt = assemble_pool(
        frozen.queries,
        frozen.constraints,
        catalog,
        sources_from_provenance(build.provenance),
        context,
    )
    if run_files(rebuilt) != dict(files):
        raise PoolError("re-assembling the pool from its provenance does not reproduce it")
    if {q.query_id for q in frozen.queries} != {s.query_id for s in build.report.queries}:
        raise PoolError("the pool report does not cover exactly the frozen queries")
    return build


# ---- freezing -------------------------------------------------------------------------------


def pool_stage(
    frozen: FrozenQueries, files: Mapping[str, bytes]
) -> tuple[dict[str, bytes], Manifest]:
    """The public files and the `pool_frozen` manifest (provenance only as its binding)."""
    public = {POOL_PATHS[role]: files[POOL_PATHS[role]] for role in POOL_PATHS}
    entries = [*frozen.manifest.entries] + [
        entry_for(role, POOL_PATHS[role], public[POOL_PATHS[role]]) for role in POOL_PATHS
    ]
    queries_manifest = frozen.manifest
    manifest = build_manifest(
        golden_version=queries_manifest.golden_version,
        stage=Stage.POOL_FROZEN,
        dataset_id=queries_manifest.dataset_id,
        dataset_version=queries_manifest.dataset_version,
        dataset_checksum_sha256=queries_manifest.dataset_checksum_sha256,
        versions=queries_manifest.versions,
        entries=tuple(sorted(entries, key=lambda e: e.path)),
        provenance_binding=sha256_hex(files[PROVENANCE_FILE]),
        previous_manifest_sha256=queries_manifest.manifest_sha256,
        supersedes_manifest_sha256=queries_manifest.supersedes_manifest_sha256,
    )
    validate_transition(queries_manifest, manifest)
    return {**public, POOL_MANIFEST_PATH: encode_manifest(manifest)}, manifest


def freeze_pool(
    golden_dir: Path,
    files: Mapping[str, bytes],
    *,
    allowed_root: Path = ALLOWED_ROOT,
    private_root: Path = PRIVATE_ROOT,
    catalog: CatalogIndex | None = None,
    link: Callable[[Path, Path], None] = os.link,
) -> tuple[Manifest, Path]:
    """Write the private provenance, then the public pool files and the manifest (last), all
    exclusively; verify; and remove everything written if any step fails."""
    catalog = catalog or load_catalog_index()
    golden_dir = freeze_queries.safe_golden_dir(golden_dir, allowed_root)
    refuse_stale_staging(golden_dir)
    frozen = load_frozen_queries(golden_dir, allowed_root=allowed_root, catalog=catalog)
    build = check_build(frozen, catalog, files)
    public, manifest = pool_stage(frozen, files)
    private_root.mkdir(parents=True, exist_ok=True)
    refuse_stale_staging(private_root)
    relative = f"{build.provenance.run_id}/{PROVENANCE_FILE}"
    provenance_path = safe_child(private_root, relative)
    write_exclusive(private_root, {relative: files[PROVENANCE_FILE]}, link=link)
    try:
        write_exclusive(golden_dir, public, last=POOL_MANIFEST_PATH, link=link)
        try:
            verify_pool(
                golden_dir,
                allowed_root=allowed_root,
                private_root=private_root,
                provenance_path=provenance_path,
                catalog=catalog,
            )
        except BaseException:
            for relative_public in public:
                safe_child(golden_dir, relative_public).unlink(missing_ok=True)
            raise
    except BaseException:
        provenance_path.unlink(missing_ok=True)
        with_parent = provenance_path.parent
        if with_parent.is_dir() and not any(with_parent.iterdir()):
            with_parent.rmdir()
        raise
    return manifest, provenance_path


# ---- verification ---------------------------------------------------------------------------


@dataclass(frozen=True)
class PoolVerification:
    manifest: Manifest
    report: PoolReport
    provenance_path: Path | None  # None with --public-only


def find_provenance(private_root: Path, binding: str) -> Path:
    """The private provenance file whose exact bytes hash to the binding."""
    if private_root.is_dir():
        for candidate in sorted(private_root.glob(f"*/{PROVENANCE_FILE}")):
            if candidate.is_file() and sha256_hex(candidate.read_bytes()) == binding:
                return candidate
    raise PoolError(
        "no private provenance file matches provenance_binding; it cannot be verified or "
        "unsealed from this checkout"
    )


def verify_pool(
    golden_dir: Path,
    *,
    allowed_root: Path = ALLOWED_ROOT,
    private_root: Path = PRIVATE_ROOT,
    provenance_path: Path | None = None,
    public_only: bool = False,
    catalog: CatalogIndex | None = None,
) -> PoolVerification:
    catalog = catalog or load_catalog_index()
    golden_dir = freeze_queries.safe_golden_dir(golden_dir, allowed_root)
    refuse_stale_staging(golden_dir)
    frozen = load_frozen_queries(golden_dir, allowed_root=allowed_root, catalog=catalog)
    manifest = decode_manifest(read_frozen(golden_dir, POOL_MANIFEST_PATH))
    if manifest.stage is not Stage.POOL_FROZEN:
        raise PoolError("expected the pool_frozen manifest")
    validate_transition(frozen.manifest, manifest)
    content: dict[str, bytes] = {}
    for role, path in POOL_PATHS.items():
        entry = manifest.entry(role)
        if entry.path != path:
            raise PoolError(f"unexpected path for {role.value}: {entry.path}")
        content[path] = read_frozen(golden_dir, path)
        verify_entry(entry, content[path])
    report = decode_json_object(content[POOL_PATHS[Role.POOL_REPORT]], PoolReport)
    pool = decode_jsonl(content[POOL_PATHS[Role.POOL]], PoolItem)
    eligibility = decode_jsonl(content[POOL_PATHS[Role.ELIGIBILITY]], EligibilityRecord)
    validate_pool(frozen.queries, pool, catalog)
    validate_eligibility(pool, frozen.constraints, eligibility)
    regenerated = [
        evaluate(i.query_id, frozen.constraints, catalog.products[i.product_id]) for i in pool
    ]
    verify_entry(
        manifest.entry(Role.ELIGIBILITY),
        content[POOL_PATHS[Role.ELIGIBILITY]],
        regenerated=encode_jsonl(regenerated),
    )
    sizes: dict[str, int] = {}
    for item in pool:
        sizes[item.query_id] = sizes.get(item.query_id, 0) + 1
    if {s.query_id: s.pool_size for s in report.queries} != sizes or not report.all_within_cap:
        raise PoolError("the pool report does not match the pool")
    if public_only:
        return PoolVerification(manifest, report, None)
    path = provenance_path or find_provenance(private_root, manifest.provenance_binding or "")
    provenance = path.read_bytes()
    if sha256_hex(provenance) != manifest.provenance_binding:
        raise PoolError("the private provenance bytes do not match provenance_binding")
    check_build(frozen, catalog, {**content, PROVENANCE_FILE: provenance})
    return PoolVerification(manifest, report, path)


# ---- running the sources (subprocesses on scratch databases) -------------------------------


def _preflight(settings) -> dict:  # pragma: no cover - reads the models and git
    from evals.runners import pool_sources as ps

    return {
        "settings": ps.check_settings(settings),
        "model_pins": ps.verify_model_pins(),
        "components": ps.component_versions(),
        "libraries": ps.library_versions(),
        "trees": ps.runtime_trees(),
    }


def child_main(database: str, out_dir: Path) -> int:  # pragma: no cover - database and models
    """One independent run: fresh scratch database, every source, deterministic assembly."""
    from ecommerce_search.config import get_settings
    from evals.runners import pool_sources as ps

    ps.install_network_guard()
    settings = get_settings()
    ps.assert_scratch_name(database, settings.postgres_db)
    checked = _preflight(settings)
    catalog = load_catalog_index()
    frozen = load_frozen_queries(DEFAULT_GOLDEN_DIR, catalog=catalog)
    context = ps.build_run_context(
        queries_manifest_sha256=frozen.manifest.manifest_sha256,
        dataset=(catalog.dataset_id, catalog.dataset_version, catalog.checksum_sha256),
        settings=checked["settings"],
        model_pins=checked["model_pins"],
        components=checked["components"],
        libraries=checked["libraries"],
        trees=checked["trees"],
    )
    pins = {v.name: v.value for v in checked["model_pins"]}
    queries = [(q.query_id, q.text) for q in sorted(frozen.queries, key=lambda q: q.query_id)]
    sources = ps.retrieve_on_scratch_database(settings, database, queries, pins)
    build = assemble_pool(frozen.queries, frozen.constraints, catalog, sources, context)
    out_dir.mkdir(parents=True, exist_ok=False)
    for name, data in run_files(build).items():
        (out_dir / name).write_bytes(data)
    return 0


def run_once(out_dir: Path) -> dict[str, bytes]:  # pragma: no cover - database and models
    """A fresh subprocess on a fresh scratch database; the database is always dropped."""
    from sqlalchemy import create_engine

    from ecommerce_search.config import get_settings
    from evals.runners import pool_sources as ps

    settings = get_settings()
    name = ps.assert_scratch_name(ps.new_scratch_name(), settings.postgres_db)
    argv = [
        sys.executable,
        "-m",
        "evals.runners.build_pool",
        "_child",
        "--database",
        name,
        "--out",
        str(out_dir),
    ]
    admin = create_engine(settings.database_url(database="postgres"), isolation_level="AUTOCOMMIT")
    try:
        try:
            subprocess.run(  # noqa: S603 - fixed argv, sys.executable
                argv, cwd=ROOT, check=True, env={**os.environ, **ps.OFFLINE_ENV}
            )
        except subprocess.CalledProcessError as exc:
            raise PoolError(f"a pool run failed (exit {exc.returncode}); nothing frozen") from None
        finally:
            from sqlalchemy import text

            with admin.connect() as conn:
                conn.execute(text(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))
            if ps.database_exists(admin, name):
                raise PoolError(f"the scratch database {name} was not dropped")
    finally:
        admin.dispose()
    return {name_: (out_dir / name_).read_bytes() for name_ in RUN_FILES}


def generate(golden_dir: Path = DEFAULT_GOLDEN_DIR) -> int:  # pragma: no cover - runs sources
    from ecommerce_search.config import get_settings
    from evals.runners import pool_sources as ps

    ps.install_network_guard()
    catalog = load_catalog_index()
    golden = freeze_queries.safe_golden_dir(golden_dir, ALLOWED_ROOT)
    refuse_stale_staging(golden)
    if os.path.lexists(golden / POOL_MANIFEST_PATH):
        raise PoolError("pool_frozen already exists; it is never regenerated in place")
    frozen = load_frozen_queries(golden, catalog=catalog)
    _preflight(get_settings())
    print(f"verified queries_frozen {frozen.manifest.manifest_sha256}")
    with tempfile.TemporaryDirectory(prefix="golden-pool-runs-") as tmp:
        outputs = []
        for run in (1, 2):
            print(f"run {run}/2: fresh scratch database, all sources at top_k=20 ...", flush=True)
            outputs.append(run_once(Path(tmp) / f"run{run}"))
        compare_runs(outputs[0], outputs[1])
        print("determinism: both runs byte-identical for " + ", ".join(RUN_FILES))
        first = decode_run(outputs[0])
        try:
            check_pool_cap(first.pool, first.provenance.entries)
        except PoolCapExceeded:
            print(report_text(first.report))
            raise
        manifest, path = freeze_pool(golden, outputs[0], catalog=catalog)
    print(f"froze pool_frozen; manifest_sha256 {manifest.manifest_sha256}")
    print(f"provenance_binding {manifest.provenance_binding}")
    print(f"private provenance (uncommitted): {path.relative_to(ROOT).as_posix()}")
    return 0


def regenerate(golden_dir: Path = DEFAULT_GOLDEN_DIR) -> int:  # pragma: no cover - runs sources
    from ecommerce_search.config import get_settings
    from evals.runners import pool_sources as ps

    ps.install_network_guard()
    checked = verify_pool(golden_dir)
    _preflight(get_settings())
    golden = freeze_queries.safe_golden_dir(golden_dir, ALLOWED_ROOT)
    frozen = {path: read_frozen(golden, path) for path in POOL_PATHS.values()}
    if checked.provenance_path is None:
        raise PoolError("the private provenance is required for regeneration")
    frozen[PROVENANCE_FILE] = checked.provenance_path.read_bytes()
    with tempfile.TemporaryDirectory(prefix="golden-pool-regen-") as tmp:
        fresh = run_once(Path(tmp) / "run")
    compare_runs(frozen, fresh)
    print("regeneration: a fresh run is byte-identical to the frozen pool and provenance")
    return 0


def report_text(report: PoolReport) -> str:
    lines = [
        f"pool policy {report.pool_policy}, source top_k {report.source_top_k}, "
        f"cap {report.max_pool_size}, completion cap {report.completion_cap}, "
        f"negatives/query {report.negatives_per_query}",
        "",
        "| query | sources (v0/dense/v1/v2/v3d10/v3d20) | union | completion | added | "
        "neg same/other/short | pool | <=cap |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for q in report.queries:
        counts = "/".join(str(c.count) for c in q.source_result_counts)
        eligible = "-" if q.eligible_count is None else str(q.eligible_count)
        lines.append(
            f"| {q.query_id} | {counts} | {q.union_size} | {q.completion.value} "
            f"(eligible {eligible}) | {q.completion_added} | {q.negatives_same_category}/"
            f"{q.negatives_other_category}/{q.negative_shortfall} | {q.pool_size} | "
            f"{'yes' if q.within_cap else 'NO'} |"
        )
    lines.append("")
    lines.append(
        f"total pool items {report.total_pool_items}; all within cap: {report.all_within_cap}"
    )
    return "\n".join(lines)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="python -m evals.runners.build_pool")
    parser.add_argument("--golden-dir", type=Path, default=DEFAULT_GOLDEN_DIR)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("generate", help="two independent runs, compare, freeze pool_frozen")
    check = commands.add_parser("verify", help="re-verify pool_frozen; writes nothing")
    check.add_argument("--public-only", action="store_true")
    commands.add_parser("regenerate", help="one fresh run compared with the frozen bytes")
    commands.add_parser("report", help="print the public aggregate pool report")
    child = commands.add_parser("_child", help=argparse.SUPPRESS)
    child.add_argument("--database", required=True)
    child.add_argument("--out", type=Path, required=True)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.command == "_child":  # pragma: no cover - database and models
            return child_main(args.database, args.out)
        if args.command == "generate":  # pragma: no cover - database and models
            return generate(args.golden_dir)
        if args.command == "regenerate":  # pragma: no cover - database and models
            return regenerate(args.golden_dir)
        if args.command == "verify":
            result = verify_pool(args.golden_dir, public_only=args.public_only)
            print(f"verified pool_frozen manifest {result.manifest.manifest_sha256}")
            if result.provenance_path is None:
                print("public files only: the private provenance was not checked")
            else:
                print(
                    "private provenance matches provenance_binding and reproduces the pool "
                    "byte for byte"
                )
            return 0
        golden = freeze_queries.safe_golden_dir(args.golden_dir, ALLOWED_ROOT)
        report = decode_json_object(read_frozen(golden, POOL_PATHS[Role.POOL_REPORT]), PoolReport)
        print(report_text(report))
    except ContractError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
