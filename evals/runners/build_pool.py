"""Generate, freeze and verify the `pool_frozen` stage of the internal Golden Dataset (M9 C2).

Subcommands:

* `generate`: preflight (stale staging, verified `queries_frozen`, approved settings, both model
  pins verified offline, clean runtime tree, network guard), then **two independent runs**,
  each a fresh subprocess on a fresh scratch database (`ecommerce_search_bench_<12 hex>`,
  migrated, seeded with the frozen catalog and embedded with the pinned model). Each run calls
  every V0–V3 source at top_k=20 and assembles the pool deterministically
  (`evals.contracts.pooling`). The two runs' public pool, eligibility, pool report and private
  provenance must be byte-identical; otherwise nothing is frozen and the first difference (file
  and line, never content) is reported. Then the pool cap is checked: over 60 for any query
  freezes nothing, trims nothing and reports aggregate counts only. Then the private provenance
  is written (exclusively) to `data/processed/golden_pool/<run_id>/provenance.json`, the public
  files and the `pool_frozen` manifest (last) are written exclusively into the golden
  directory, and the result is verified; any failure removes everything this run wrote.
* `verify`: read-only. Re-verifies `queries_frozen`, the `pool_frozen` manifest and transition,
  every entry's bytes, the pool (catalog content and card hashes, blind order, cap), the
  eligibility (regenerated byte for byte), the report, and, unless `--public-only`, the private
  provenance: its exact bytes must hash to `provenance_binding`, and re-assembling the pool from
  it must reproduce every public file and the provenance byte for byte.
* `regenerate`: one more fresh run (database and models), compared byte for byte with the
  frozen files and the private provenance. Writes nothing.
* `report`: prints the public aggregate pool report. Never prints product-level provenance.

The private provenance is never a manifest entry before `provenance_unsealed` (D12) and is never
printed. Pool generation writes no judgement, label, consistency sample or metric file.

Usage:
  uv run --offline python -m evals.runners.build_pool generate
  uv run --offline python -m evals.runners.build_pool verify [--public-only]
  uv run --offline python -m evals.runners.build_pool regenerate
  uv run --offline python -m evals.runners.build_pool report
"""

