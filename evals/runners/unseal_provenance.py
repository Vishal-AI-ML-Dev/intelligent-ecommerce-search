from evals.runners.golden_io import FreezeError, read_frozen, write_exclusive

UNSEALED_MANIFEST_PATH = "manifests/6-provenance_unsealed.json"
PROVENANCE_PATH = "provenance.json"
# The complete chain this runner works on; any further manifest refuses it.
FROZEN_CHAIN = (
    freeze_queries.MANIFEST_PATH,
    build_pool.POOL_MANIFEST_PATH,
    seal_primary.SEALED_MANIFEST_PATH,
    seal_second_review.SECOND_REVIEW_MANIFEST_PATH,
    freeze_labels.LABELS_MANIFEST_PATH,
)


class UnsealError(FreezeError):
    """The provenance cannot be checked or unsealed; nothing was written."""


@dataclass(frozen=True)
class UnsealInputs:
    golden_dir: Path
    manifest: Manifest  # labels_frozen
    provenance_path: Path
    provenance_data: bytes
    provenance: PoolProvenance


def _role_files(manifest: Manifest, golden: Path) -> dict[Role, bytes]:
    files = {e.role: read_frozen(golden, e.path) for e in manifest.entries}
    for entry in manifest.entries:
        verify_entry(entry, files[entry.role])
    return files


def load_labels_frozen(
    golden_dir: Path,
    *,
    allowed_root: Path = build_pool.ALLOWED_ROOT,
    catalog: CatalogIndex | None = None,
    chain: tuple[str, ...] = FROZEN_CHAIN,
) -> tuple[Path, Manifest]:
    """Re-verify the whole review-2 chain through `labels_frozen` (see the module docstring).
    Returns the golden directory and the verified `labels_frozen` manifest. `chain` names the
    exact manifest files that must be present: by default the chain through `labels_frozen`;
    a later reader passes the chain through the stage it verifies itself."""
    sealed = load_sealed(
        golden_dir, allowed_root=allowed_root, catalog=catalog, primary_labels=True
    )
    golden = sealed.golden_dir
    present = sorted(p.name for p in (golden / "manifests").iterdir())
    if present != sorted(Path(p).name for p in chain):
        last = Path(chain[-1]).stem.split("-", 1)[1]
        raise UnsealError(
            f"expected exactly the chain through {last} and no later stage; found {present!r}"
        )
    second = decode_manifest(read_frozen(golden, seal_second_review.SECOND_REVIEW_MANIFEST_PATH))
    if (
        second.stage is not Stage.SECOND_REVIEW_SEALED
        or second.review_protocol != REVIEW_PROTOCOL_2
    ):
        raise UnsealError("expected the review-2 second_review_sealed manifest")
    validate_transition(sealed.manifest, second)
    labels = freeze_labels.verify_written(golden, second)
    if labels.stage is not Stage.LABELS_FROZEN or labels.review_protocol != REVIEW_PROTOCOL_2:
        raise UnsealError("expected the review-2 labels_frozen manifest")
    files = _role_files(labels, golden)

    primaries = sealed.primaries or ()
    eligibility = list(sealed.eligibility.values())
    reviews = decode_jsonl(files[Role.SECOND_REVIEW_JUDGEMENTS], Judgement)
    report = decode_json_object(files[Role.AGREEMENT_REPORT], AgreementReport)
    validate_second_review_round(
        primaries,
        sealed.sample,
        reviews,
        eligibility,
        labels.primary_seal_sha256(),
        labels.primary_sealed_at,  # type: ignore[arg-type]
        report.second_review_sealed_at,
    )
    verify_entry(
        labels.entry(Role.AGREEMENT_REPORT),
        files[Role.AGREEMENT_REPORT],
        regenerated=encode_json_object(
            build_agreement_report(
                primaries,
                sealed.sample,
                reviews,
                primary_annotator=validate_single_annotator(primaries),
                second_annotator=SECOND_REVIEWER_HANDLE,
                second_review_sha256=labels.entry(Role.SECOND_REVIEW_JUDGEMENTS).file_sha256,
                second_review_sealed_at=report.second_review_sealed_at,
            )
        ),
    )
    adjudications = decode_jsonl(files[Role.ADJUDICATION_JUDGEMENTS], Judgement)
    consensus = decode_jsonl(files[Role.CONSENSUS_ADJUDICATIONS], ConsensusAdjudication)
    validate_review_2_adjudication(
        primaries,
        reviews,
        decode_jsonl(files[Role.ADJUDICATION_QUEUE], QueueItem),
        decode_jsonl(files[Role.JOINT_RESOLUTION_QUEUE], JointResolutionItem),
        adjudications,
        consensus,
        decode_jsonl(files[Role.LABEL_CHANGES], LabelChange),
        labels.golden_version,
        primary_sealed_at=labels.primary_sealed_at,  # type: ignore[arg-type]
        report=report,
    )
    validate_judgements_against_eligibility(adjudications, eligibility)
    for record in consensus:
        pair = (record.query_id, record.product_id)
        if record.label is Label.RELEVANT and (
            sealed.eligibility[pair].hard_overall is OverallStatus.VIOLATED
        ):
            raise UnsealError(f"{pair!r}: relevant but a hard constraint is violated")
    validate_final_judgements_review_2(
        primaries,
        adjudications,
        consensus,
        decode_jsonl(files[Role.FINAL_JUDGEMENTS], FinalJudgement),
    )
    validate_partitions(
        list(sealed.queries.values()),
        decode_jsonl(files[Role.PARTITIONS], PartitionAssignment),
    )
    return golden, labels


def check(
    golden_dir: Path,
    *,
    allowed_root: Path = build_pool.ALLOWED_ROOT,
    private_root: Path = build_pool.PRIVATE_ROOT,
    catalog: CatalogIndex | None = None,
) -> UnsealInputs:
    golden, labels = load_labels_frozen(golden_dir, allowed_root=allowed_root, catalog=catalog)
    verified = build_pool.verify_pool(
        golden, allowed_root=allowed_root, private_root=private_root, catalog=catalog
    )
    if verified.provenance_path is None:  # pragma: no cover - public_only is never set here
        raise UnsealError("the private provenance was not checked")
    data = verified.provenance_path.read_bytes()
    if sha256_hex(data) != labels.provenance_binding:
        raise UnsealError("the private provenance bytes do not match provenance_binding")
    return UnsealInputs(
        golden_dir=golden,
        manifest=labels,
        provenance_path=verified.provenance_path,
        provenance_data=data,
        provenance=decode_json_object(data, PoolProvenance),
    )


def unseal(
    golden_dir: Path,
    *,
    confirm_unseal: bool,
    labels_frozen_sha256: str,
    provenance_sha256: str,
    allowed_root: Path = build_pool.ALLOWED_ROOT,
    private_root: Path = build_pool.PRIVATE_ROOT,
    catalog: CatalogIndex | None = None,
    link: Callable[[Path, Path], None] = os.link,
) -> Manifest:
    if not confirm_unseal:
        raise UnsealError("refused: --confirm-unseal is the explicit authorization to unseal")
    inputs = check(
        golden_dir, allowed_root=allowed_root, private_root=private_root, catalog=catalog
    )
    previous = inputs.manifest
    if previous.manifest_sha256 != labels_frozen_sha256:
        raise UnsealError("refused: the labels_frozen manifest differs from the reviewed SHA-256")
    if sha256_hex(inputs.provenance_data) != provenance_sha256:
        raise UnsealError("refused: the provenance differs from the reviewed SHA-256")
    entries = [
        *previous.entries,
        entry_for(Role.PROVENANCE, PROVENANCE_PATH, inputs.provenance_data),
    ]
    manifest = build_manifest(
        golden_version=previous.golden_version,
        stage=Stage.PROVENANCE_UNSEALED,
        dataset_id=previous.dataset_id,
        dataset_version=previous.dataset_version,
        dataset_checksum_sha256=previous.dataset_checksum_sha256,
        versions=previous.versions,
        entries=tuple(sorted(entries, key=lambda e: e.path)),
        provenance_binding=previous.provenance_binding,
        primary_sealed_at=previous.primary_sealed_at,
        labels_frozen_at=previous.labels_frozen_at,
        previous_manifest_sha256=previous.manifest_sha256,
        supersedes_manifest_sha256=previous.supersedes_manifest_sha256,
        review_protocol=previous.review_protocol,
    )
    validate_transition(previous, manifest)
    files = {
        PROVENANCE_PATH: inputs.provenance_data,
        UNSEALED_MANIFEST_PATH: encode_manifest(manifest),
    }
    write_exclusive(inputs.golden_dir, files, last=UNSEALED_MANIFEST_PATH, link=link)
    written = verify_unsealed(
        inputs.golden_dir, previous, allowed_root=allowed_root, catalog=catalog
    )
    if written != manifest:  # pragma: no cover - the bytes were just verified by hash
        raise UnsealError("the written manifest differs from the one built")
    if inputs.provenance_path.read_bytes() != inputs.provenance_data:
        raise UnsealError("the private provenance changed during unsealing")
    return written


def verify_unsealed(
    golden: Path,
    previous: Manifest,
    *,
    allowed_root: Path = build_pool.ALLOWED_ROOT,
    catalog: CatalogIndex | None = None,
) -> Manifest:
    """Re-read the written stage: the next legal transition, every entry matches its bytes, the
    provenance entry equals the binding, and an offline re-assembly from the written copy
    reproduces the frozen pool files and the provenance byte for byte."""
    written = decode_manifest(read_frozen(golden, UNSEALED_MANIFEST_PATH))
    validate_transition(previous, written)
    _role_files(written, golden)
    if written.entry(Role.PROVENANCE).file_sha256 != written.provenance_binding:
        raise UnsealError("the unsealed provenance does not match its binding")
    build_pool.verify_pool(
        golden,
        allowed_root=allowed_root,
        provenance_path=golden / written.entry(Role.PROVENANCE).path,
        catalog=catalog,
    )
    return written


def summary_lines(inputs: UnsealInputs) -> list[str]:
    """Hashes and aggregate counts only; never product-level provenance."""
    provenance = inputs.provenance
    return [
        f"labels_frozen_sha256 {inputs.manifest.manifest_sha256}",
        f"labels_frozen_at {inputs.manifest.labels_frozen_at.isoformat()}",  # type: ignore[union-attr]
        f"provenance_binding {inputs.manifest.provenance_binding}",
        f"provenance_sha256 {sha256_hex(inputs.provenance_data)}",
        f"provenance run_id {provenance.run_id}: {len(provenance.source_runs)} source runs, "
        f"{len(provenance.entries)} pooled-product entries",
        "offline re-assembly from the provenance reproduces the frozen pool files byte for byte",
    ]


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="python -m evals.runners.unseal_provenance")
    parser.add_argument("--golden-dir", type=Path, default=build_pool.DEFAULT_GOLDEN_DIR)
    parser.add_argument("--private-root", type=Path, default=build_pool.PRIVATE_ROOT)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("check", help="verify the frozen chain and the private provenance")
    run = commands.add_parser("unseal", help="authorized transition to provenance_unsealed")
    run.add_argument("--confirm-unseal", action="store_true")
    run.add_argument("--labels-frozen-sha256", required=True)
    run.add_argument("--provenance-sha256", required=True)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        if args.command == "check":
            for line in summary_lines(check(args.golden_dir, private_root=args.private_root)):
                print(line)
        else:
            manifest = unseal(
                args.golden_dir,
                confirm_unseal=args.confirm_unseal,
                labels_frozen_sha256=args.labels_frozen_sha256,
                provenance_sha256=args.provenance_sha256,
                private_root=args.private_root,
            )
            print(f"unsealed provenance; manifest_sha256 {manifest.manifest_sha256}")
    except (ContractError, OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
