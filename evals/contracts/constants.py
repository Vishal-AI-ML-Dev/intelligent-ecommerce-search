class Label(StrEnum):
    """The repository-mandated three-level relevance label (spec §6.7, D1)."""

    RELEVANT = "relevant"
    BORDERLINE = "borderline"
    NOT_RELEVANT = "not_relevant"


# Fixed label order (used by the consistency allocation and confusion matrices).
LABEL_ORDER: tuple[Label, ...] = (Label.RELEVANT, Label.BORDERLINE, Label.NOT_RELEVANT)


class Relation(StrEnum):
    EXACT_MATCH = "exact_match"
    SATISFIES_INTENT = "satisfies_intent"
    SUBSTITUTE = "substitute"
    PARTIAL = "partial"
    COMPLEMENT = "complement"
    OFF_TARGET = "off_target"
    OUT_OF_CATALOG = "out_of_catalog"


ALLOWED_RELATIONS: MappingProxyType[Label, frozenset[Relation]] = MappingProxyType(
    {
        Label.RELEVANT: frozenset({Relation.EXACT_MATCH, Relation.SATISFIES_INTENT}),
        Label.BORDERLINE: frozenset({Relation.SUBSTITUTE, Relation.PARTIAL}),
        Label.NOT_RELEVANT: frozenset(
            {Relation.COMPLEMENT, Relation.OFF_TARGET, Relation.OUT_OF_CATALOG}
        ),
    }
)

# D2: graded gains for NDCG, and the two binary definitions. Both binary definitions are always
# reported; no blended headline score is produced.
NDCG_GAINS: MappingProxyType[Label, int] = MappingProxyType(
    {Label.RELEVANT: 2, Label.BORDERLINE: 1, Label.NOT_RELEVANT: 0}
)
STRICT_RELEVANT: frozenset[Label] = frozenset({Label.RELEVANT})
LENIENT_RELEVANT: frozenset[Label] = frozenset({Label.RELEVANT, Label.BORDERLINE})
