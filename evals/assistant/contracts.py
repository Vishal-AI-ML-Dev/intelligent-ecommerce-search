"""Assistant evaluation case format `aq-2` (Milestone 17).

One case is one shopper message, the catalog records a fixed retriever returns for it, optional
scripted (mock) provider results, and the behaviour the case author expects. Cases run through
the real M16 workflow (`assistant.workflow.answer`); only retrieval is fixed, and generation is
either scripted (mocked runs) or the real provider (live runs, owner-approved only).

Split and evidence:

* `split`: `dev` cases (the synthetic fixtures, smoke-style cases) are for harness development
  and never scored as M17 evidence. `eval` cases form the bounded M17 evaluation set.
* `evidence_source`: `synthetic` (hand-written records), `captured_v3` (the V3 search results
  for the message, captured once from the local catalog and then frozen; `evidence_capture`
  records how), or `captured_v3_injected` (a captured set in which the records named by
  `counterpart.injected_product_ids` were copied and given injected text; only for an injected
  counterpart). Evidence is frozen, so a run measures the workflow and the provider, not
  retrieval drift. A captured set may be empty or may not fit the request: whether the request
  should be answered, clarified or abstained on is the author's `expect`, never assumed from the
  evidence size.
* An `eval` case is never a `synthetic_test_fixture` and never uses `synthetic` evidence.

Authorship, review and handles:

* `authorship` says who wrote the case and never changes: an AI-authored case that a human
  reviews or edits stays `ai_authored`.
* `case_review` records that a reviewer approved or revised the case and its expectations. It
  is entered by the reviewer, never set by loading, running or passing checks.
* `ann-<n>` handles record provenance (who the record says acted). They are pseudonymous and do
  not prove human identity.
* Human answer judgements live in a separate file (`judgements.py`, `aj-1`).

Counterparts: an injected case names its clean counterpart. A `message` injection keeps the
evidence identical and changes the message; a `listing` injection keeps the message and the
record list identical and changes only free text (title, subcategory, description) of the
named records. Reports compare the pair's behaviour, not only whether an injected item was chosen.

Expectations are written by the case author by hand, never generated by the code under test.
"""

import hashlib
import json
import re
from datetime import date, datetime
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from ecommerce_search.assistant.models import (
    AbstainReason,
    ClarifyReason,
    ConstraintField,
    EvidenceProduct,
    Outcome,
)
from ecommerce_search.generation.provider import GenerationFailure, GroundedDraft

SCHEMA_VERSION = "aq-2"
Tag = Literal[
    "grounded_answer",
    "constraint",
    "clarification",
    "abstention",
    "prompt_injection",
    "malicious_listing",
    "false_refusal",
    "degradation",
]
Authorship = Literal["synthetic_test_fixture", "ai_authored", "human_authored"]
CheckStatus = Literal["passed", "failed", "not_verified"]
HANDLE = re.compile(r"^ann-[0-9]+$")
FREE_TEXT_FIELDS = ("title", "subcategory", "description")


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class ScriptedResult(_Frozen):
    """One mock provider response: a draft xor a failure code."""

    draft: GroundedDraft | None = None
    failure: GenerationFailure | None = None
    input_tokens: int | None = None
    output_tokens: int | None = None

    @model_validator(mode="after")
    def _one_of(self) -> "ScriptedResult":
        if (self.draft is None) == (self.failure is None):
            raise ValueError("exactly one of draft and failure must be set")
        return self


class EvidenceCapture(_Frozen):
    search_version: str = Field(min_length=1)
    top_k: int = Field(ge=1, le=50)
    captured_at: datetime


class CaseReview(_Frozen):
    reviewer_handle: str = Field(pattern=HANDLE.pattern)
    reviewed_on: date
    decision: Literal["approved", "revised"]


class Counterpart(_Frozen):
    clean_case_id: str
    injection_site: Literal["message", "listing"]
    injected_product_ids: tuple[str, ...] = ()


class Expectation(_Frozen):
    outcome: Outcome
    clarify_reason: ClarifyReason | None = None
    # Acceptable abstain reasons when the outcome is `abstain` (any one passes).
    abstain_reasons: tuple[AbstainReason, ...] = ()
    # Exact set of recommended product IDs (mocked cases); None = not checked.
    recommended_ids: tuple[str, ...] | None = None
    # Every recommended ID must be in this set (live cases); None = not checked.
    acceptable_recommendation_ids: tuple[str, ...] | None = None
    # Must never be recommended. They may (and often must) stay visible as search evidence.
    forbidden_recommendation_ids: tuple[str, ...] = ()
    # Must remain in the displayed evidence (search results), recommended or not.
    required_evidence_ids: tuple[str, ...] = ()
    # product_id -> field -> status, for recommended products.
    constraint_statuses: dict[str, dict[ConstraintField, CheckStatus]] = {}
    max_generation_calls: int = Field(default=2, ge=0, le=2)

    @model_validator(mode="after")
    def _reasons(self) -> "Expectation":
        if (self.outcome == "abstain") != bool(self.abstain_reasons):
            raise ValueError("abstain_reasons are required for, and only for, outcome abstain")
        if (self.outcome == "clarify") != (self.clarify_reason is not None):
            raise ValueError("clarify_reason is required for, and only for, outcome clarify")
        return self


class EvalCase(_Frozen):
    schema_version: Literal["aq-2"]
    case_id: str = Field(pattern=r"^[a-z0-9][a-z0-9-]{2,63}$")
    split: Literal["dev", "eval"]
    tags: tuple[Tag, ...] = Field(min_length=1)
    authorship: Authorship
    author: str = Field(min_length=1, max_length=64)
    case_review: CaseReview | None = None
    message: str = Field(min_length=1, max_length=1000)
    generation: Literal["on", "off"] = "on"
    evidence_source: Literal["synthetic", "captured_v3", "captured_v3_injected"]
    evidence_capture: EvidenceCapture | None = None
    evidence: tuple[EvidenceProduct, ...] = ()
    counterpart: Counterpart | None = None
    scripted: tuple[ScriptedResult, ...] = Field(default=(), max_length=2)
    expect: Expectation

    @model_validator(mode="after")
    def _consistent(self) -> "EvalCase":
        if self.authorship == "human_authored" and not HANDLE.match(self.author):
            raise ValueError("human_authored cases need a pseudonymous ann-<n> author handle")
        if self.authorship != "human_authored" and HANDLE.match(self.author):
            raise ValueError("an ann-<n> handle is reserved for human_authored cases")
        if self.authorship == "synthetic_test_fixture" and self.case_review is not None:
            raise ValueError("synthetic test fixtures are not reviewed cases")
        if self.split == "eval" and (
            self.authorship == "synthetic_test_fixture" or self.evidence_source == "synthetic"
        ):
            raise ValueError("eval cases need non-fixture authorship and captured evidence")
        if (self.evidence_source == "synthetic") != (self.evidence_capture is None):
            raise ValueError("evidence_capture is required for, and only for, captured evidence")
        injected = self.counterpart is not None and self.counterpart.injection_site == "listing"
        if (self.evidence_source == "captured_v3_injected") != (injected and self.split == "eval"):
            raise ValueError("captured_v3_injected is only for eval listing-injection counterparts")
        if self.generation == "off" and self.scripted:
            raise ValueError("a generation-off case cannot script provider results")
        ids = [product.product_id for product in self.evidence]
        if len(set(ids)) != len(ids):
            raise ValueError("duplicate evidence product_id")
        return self


def _check_counterpart(case: EvalCase, pair: Counterpart, by_id: dict[str, EvalCase]) -> None:
    clean = by_id.get(pair.clean_case_id)
    if clean is None or clean.counterpart is not None or clean.split != case.split:
        raise ValueError(f"{case.case_id}: clean counterpart must exist, be clean, same split")
    if pair.injection_site == "message":
        if case.evidence != clean.evidence or case.message == clean.message:
            raise ValueError(f"{case.case_id}: message injection must keep the evidence only")
        if pair.injected_product_ids:
            raise ValueError(f"{case.case_id}: a message injection names no injected products")
        return
    if case.message != clean.message:
        raise ValueError(f"{case.case_id}: listing injection must keep the message")
    if [p.product_id for p in case.evidence] != [p.product_id for p in clean.evidence]:
        raise ValueError(f"{case.case_id}: listing injection must keep the record list")
    injected = set(pair.injected_product_ids)
    if not injected:
        raise ValueError(f"{case.case_id}: listing injection must name injected products")
    for mine, theirs in zip(case.evidence, clean.evidence, strict=True):
        if mine.product_id not in injected:
            if mine != theirs:
                raise ValueError(f"{case.case_id}: {mine.product_id} differs but is not injected")
            continue
        keep = set(EvidenceProduct.model_fields) - set(FREE_TEXT_FIELDS)
        if mine.model_dump(include=keep) != theirs.model_dump(include=keep) or mine == theirs:
            raise ValueError(f"{case.case_id}: {mine.product_id} must differ in free text only")


def case_sha256(case: EvalCase) -> str:
    """SHA-256 of a case's content, excluding its review (the review records this value)."""
    return hashlib.sha256(case.model_dump_json(exclude={"case_review"}).encode()).hexdigest()


def file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_cases(path: Path) -> tuple[EvalCase, ...]:
    """Reads a JSONL case file; refuses other schema versions, duplicate case IDs, mixed splits
    and inconsistent counterparts."""
    cases: list[EvalCase] = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        record = json.loads(line)
        if record.get("schema_version") != SCHEMA_VERSION:
            raise ValueError(f"line {number}: schema_version must be {SCHEMA_VERSION}")
        cases.append(EvalCase.model_validate(record))
    if not cases:
        raise ValueError("no cases")
    by_id = {case.case_id: case for case in cases}
    if len(by_id) != len(cases):
        raise ValueError("duplicate case_id")
    if len({case.split for case in cases}) != 1:
        raise ValueError("a case file holds one split")
    for case in cases:
        if case.counterpart is not None:
            _check_counterpart(case, case.counterpart, by_id)
    return tuple(cases)
