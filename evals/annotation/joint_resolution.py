"""Recording tool for the review-2 joint resolutions of the sealed joint-resolution queue (M9).

This is joint adjudication by BOTH human annotators (`ann-1` and `ann-2`) together, not a blind
round: for each routed pair it shows the query, the product card, the hard-constraint status,
both sealed judgements (primary and second review) and every routed reason, and, if the pair is
also in `ann-1`'s targeted queue, those targeted reasons (the joint record settles that item).

Scope: exactly the pairs of the sealed `joint_resolution_queue.jsonl`. Inputs are read only
from the verified chain (`adjudication.load_targeted`: everything through
`second_review_sealed` re-verified, the agreement report and the joint queue regenerated byte
for byte, no later manifest). The second-review judgements and the agreement report are read
again from their verified manifest entries. Nothing in the golden directory, and nothing in the
single-annotator adjudication work directory, is ever written.

A record exists only for a resolution both annotators have actually reached. For each pair the
operator first chooses to record a reached resolution or to skip it; a skipped pair has no
record, stays unresolved and blocks the label freeze. A record needs, step by step, with nothing
prefilled or suggested: the agreed label and relation, the joint rationale (always required), a
label-change reason when the agreed label differs from the primary label, then a summary that
each participant confirms by typing their own handle, then an explicit `y` to save. The reasons
recorded are exactly the routed reasons; both participants are recorded; `changes_label` is
whether the agreed label differs from the primary label. Catalog issues are noted in the
rationale only; catalog data is never edited. `relevant` is refused for a hard-constraint
violation.

Work directory (git-ignored, `data/processed/golden_joint_resolution/<manifest sha[:16]>/`):

* `binding.json`: binds the work to the sealed second-review manifest, the primary and
  second-review judgements, the joint queue, the agreement report, both participants, the rubric
  and the golden version, with a `created_at` (written once, never before the second-review
  seal);
* `consensus_label_changes.jsonl`: one `consensus` `LabelChange` per record that changes the
  label (none otherwise), `changed_by` the participant recording the session (`--recorded-by`);
* `consensus_adjudications.jsonl`: canonical `ConsensusAdjudication` records;
* `joint_resolution.lock` while a session runs (exclusive; never removed automatically).

Both files are atomically replaced after every confirmed record, the label changes first. An
interruption between the two writes can therefore only leave a label change for a pair that has
no record yet; the next locked session removes it (the pair is asked again) and says so.

Usage:
  uv run python -m evals.annotation.joint_resolution status
  uv run python -m evals.annotation.joint_resolution validate
  uv run python -m evals.annotation.joint_resolution annotate --recorded-by ann-1
"""

