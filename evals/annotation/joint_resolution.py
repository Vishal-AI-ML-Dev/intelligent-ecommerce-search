class JointResolutionError(ContractError):
    """Joint resolution cannot start or a record cannot be stored; nothing was written."""


class JointBinding(BaseModel):
    """Binds a work directory to one sealed second-review stage and to both participants."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    schema_version: Literal[1] = 1
    second_review_manifest_sha256: Sha256
    primary_judgements_sha256: Sha256
    second_review_judgements_sha256: Sha256
    joint_resolution_queue_sha256: Sha256
    agreement_report_sha256: Sha256
    participants: tuple[Literal["ann-1"], Literal["ann-2"]] = ("ann-1", "ann-2")
    rubric_version: str
    golden_version: int
    created_at: UtcTimestamp

    def sort_key(self) -> tuple[str, ...]:
        return (self.second_review_manifest_sha256,)


class LockInfo(BaseModel):
    """Diagnostic content of `joint_resolution.lock` (no path, name or secret)."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    second_review_manifest_sha256: Sha256
    recorded_by: Literal["ann-1", "ann-2"]
    pid: int
    started_at: UtcTimestamp


@dataclass(frozen=True)
class JointContext:
    """The verified sealed stage, the routed pairs (queue order) and both sealed rounds."""

    targeted: TargetedContext
    items: tuple[JointResolutionItem, ...]
    second_reviews: dict[Pair, Judgement]
    report: AgreementReport

    @property
    def pairs(self) -> dict[Pair, JointResolutionItem]:
        return {(i.query_id, i.product_id): i for i in self.items}


def load_joint(
    golden_dir: Path = build_pool.DEFAULT_GOLDEN_DIR,
    *,
    allowed_root: Path = build_pool.ALLOWED_ROOT,
    catalog: CatalogIndex | None = None,
) -> JointContext:
    targeted = load_targeted(golden_dir, allowed_root=allowed_root, catalog=catalog)
    golden = targeted.sealed.golden_dir
    manifest = targeted.manifest
    data = {}
    for role in (Role.SECOND_REVIEW_JUDGEMENTS, Role.AGREEMENT_REPORT, Role.JOINT_RESOLUTION_QUEUE):
        entry = manifest.entry(role)
        data[role] = read_frozen(golden, entry.path)
        verify_entry(entry, data[role])
    second = decode_jsonl(data[Role.SECOND_REVIEW_JUDGEMENTS], Judgement)
    report = decode_json_object(data[Role.AGREEMENT_REPORT], AgreementReport)
    items = tuple(decode_jsonl(data[Role.JOINT_RESOLUTION_QUEUE], JointResolutionItem))
    if {(i.query_id, i.product_id) for i in items} != set(targeted.joint):
        raise JointResolutionError("the joint queue differs from its verified regeneration")
    if tuple(sorted((report.primary_annotator, report.second_annotator))) != PARTICIPANTS:
        raise JointResolutionError("the agreement report names other annotators")
    return JointContext(
        targeted=targeted,
        items=items,
        second_reviews={(j.query_id, j.product_id): j for j in second},
        report=report,
    )


def validate_records(
    context: JointContext,
    records: Sequence[ConsensusAdjudication],
    changes: Sequence[LabelChange],
    *,
    now: datetime,
    binding_created_at: datetime,
) -> None:
    """Every record is for a routed pair, at most once, resolves exactly its routed reasons,
    names both annotators and both sealed labels, uses the primary rubric, keeps the hard
    constraint rule, and is dated inside the work window. Every changed label has exactly one
    matching consensus LabelChange by a participant, dated no earlier than its record; there is
    no other change. (The completeness check, every routed pair resolved, belongs to the
    freeze gate `validate_review_2_adjudication`; unresolved pairs are allowed while working.)"""
    targeted = context.targeted
    sealed_at = targeted.second_review_sealed_at
    if binding_created_at < sealed_at or binding_created_at > now:
        raise JointResolutionError("the work binding's created_at is outside the allowed window")
    routed = context.pairs
    seen: dict[Pair, ConsensusAdjudication] = {}
    for r in records:
        pair = (r.query_id, r.product_id)
        if pair not in routed:
            raise JointResolutionError(f"{pair!r}: not a pair of the joint-resolution queue")
        if pair in seen:
            raise JointResolutionError(f"{pair!r}: duplicate joint record")
        seen[pair] = r
        primary = targeted.primaries[pair]
        if r.reasons != routed[pair].reasons:
            raise JointResolutionError(f"{pair!r}: must resolve exactly its routed reasons")
        if r.participants != PARTICIPANTS:
            raise JointResolutionError(f"{pair!r}: a joint record must name both annotators")
        if r.primary_label is not primary.label:
            raise JointResolutionError(f"{pair!r}: primary_label differs from the sealed label")
        if r.second_review_label is not context.second_reviews[pair].label:
            raise JointResolutionError(f"{pair!r}: second_review_label differs from the seal")
        if r.rubric_version != primary.rubric_version:
            raise JointResolutionError(f"{pair!r}: consensus under a different rubric")
        if r.decided_at < binding_created_at or r.decided_at > now:
            raise JointResolutionError(f"{pair!r}: decided_at is outside the allowed window")
        status = targeted.sealed.eligibility[pair].hard_overall
        if r.label is Label.RELEVANT and status is OverallStatus.VIOLATED:
            raise JointResolutionError(f"{pair!r}: relevant but a hard constraint is violated")
    by_pair: dict[Pair, LabelChange] = {}
    for c in changes:
        pair = (c.query_id, c.product_id)
        if c.kind is not LabelChangeKind.CONSENSUS:
            raise JointResolutionError(f"{pair!r}: only consensus label changes belong here")
        if pair in by_pair:
            raise JointResolutionError(f"{pair!r}: at most one consensus label change per pair")
        by_pair[pair] = c
    changed = {pair for pair, r in seen.items() if r.changes_label}
    if set(by_pair) != changed:
        raise JointResolutionError("every changed label needs exactly one consensus LabelChange")
    for pair, c in by_pair.items():
        r = seen[pair]
        if c.previous_label is not r.primary_label or c.new_label is not r.label:
            raise JointResolutionError(f"{pair!r}: LabelChange does not match primary → consensus")
        if c.changed_by not in r.participants:
            raise JointResolutionError(f"{pair!r}: LabelChange by someone outside the consensus")
        if c.changed_at < r.decided_at or c.changed_at > now:
            raise JointResolutionError(f"{pair!r}: LabelChange is outside the allowed window")
        if (c.from_golden_version, c.to_golden_version) != (
            targeted.golden_version,
            targeted.golden_version,
        ):
            raise JointResolutionError(f"{pair!r}: LabelChange golden version differs")


class JointStore:
    """The atomically replaced working files of one sealed stage's joint resolutions."""

    def __init__(self, context: JointContext, work_root: Path = WORK_ROOT) -> None:
        self.context = context
        manifest = context.targeted.manifest
        self.directory = work_root / manifest.manifest_sha256[:16]
        self.path = self.directory / RECORDS_FILE
        self.changes_path = self.directory / CHANGES_FILE
        self.binding_path = self.directory / BINDING_FILE
        self.lock_path = self.directory / LOCK_FILE

    def expected_binding(self, created_at: datetime) -> JointBinding:
        targeted = self.context.targeted
        entry = targeted.manifest.entry
        return JointBinding(
            second_review_manifest_sha256=targeted.manifest.manifest_sha256,
            primary_judgements_sha256=entry(Role.PRIMARY_JUDGEMENTS).file_sha256,
            second_review_judgements_sha256=entry(Role.SECOND_REVIEW_JUDGEMENTS).file_sha256,
            joint_resolution_queue_sha256=entry(Role.JOINT_RESOLUTION_QUEUE).file_sha256,
            agreement_report_sha256=entry(Role.AGREEMENT_REPORT).file_sha256,
            rubric_version=targeted.rubric_version,
            golden_version=targeted.golden_version,
            created_at=created_at,
        )

    def read_binding(self, *, now: datetime) -> JointBinding | None:
        if self.directory.exists():
            refuse_stale_staging(self.directory)
        if not self.binding_path.exists():
            if self.path.exists() or self.changes_path.exists():
                raise JointResolutionError("joint-resolution files exist without their binding")
            return None
        stored = decode_json_object(self.binding_path.read_bytes(), JointBinding)
        if stored != self.expected_binding(stored.created_at):
            raise JointResolutionError(
                "the work directory is bound to another sealed stage, participants or rubric"
            )
        sealed_at = self.context.targeted.second_review_sealed_at
        if stored.created_at < sealed_at or stored.created_at > now:
            raise JointResolutionError(
                "the work binding's created_at is outside the allowed window"
            )
        return stored

    def initialize(self, *, now: datetime) -> JointBinding:
        existing = self.read_binding(now=now)
        if existing is not None:
            return existing
        binding = self.expected_binding(now)
        self.directory.mkdir(parents=True, exist_ok=True)
        _exclusive_write(self.binding_path, encode_json_object(binding))
        return binding

    def _read(self) -> tuple[list[ConsensusAdjudication], list[LabelChange]]:
        records = (
            decode_jsonl(self.path.read_bytes(), ConsensusAdjudication)
            if self.path.exists()
            else []
        )
        changes = (
            decode_jsonl(self.changes_path.read_bytes(), LabelChange)
            if self.changes_path.exists()
            else []
        )
        return records, changes

    def orphans(
        self, records: Sequence[ConsensusAdjudication], changes: Sequence[LabelChange]
    ) -> list[LabelChange]:
        """Label changes for pairs with no record: the trace of an interrupted save."""
        recorded = {(r.query_id, r.product_id) for r in records}
        return [c for c in changes if (c.query_id, c.product_id) not in recorded]

    def load(self, *, now: datetime) -> tuple[list[ConsensusAdjudication], list[LabelChange]]:
        binding = self.read_binding(now=now)
        if binding is None:
            return [], []
        records, changes = self._read()
        if self.orphans(records, changes):
            raise JointResolutionError(
                f"{CHANGES_FILE} holds a label change for a pair with no joint record (an "
                "interrupted save); the next annotate session removes it"
            )
        validate_records(
            self.context, records, changes, now=now, binding_created_at=binding.created_at
        )
        return records, changes

    def repair_interrupted_save(self, *, now: datetime) -> int:
        """Under the lock only: drop label changes whose record was never written."""
        records, changes = self._read()
        orphans = self.orphans(records, changes)
        if orphans:
            kept = [c for c in changes if c not in orphans]
            _atomic_write(self.changes_path, encode_jsonl(sorted(kept, key=lambda c: c.sort_key())))
        return len(orphans)

    def save(
        self,
        records: Sequence[ConsensusAdjudication],
        changes: Sequence[LabelChange],
        *,
        now: datetime,
    ) -> None:
        binding = self.read_binding(now=now)
        if binding is None:
            raise JointResolutionError("joint-resolution work is not initialized (no binding)")
        records = sorted(records, key=lambda r: r.sort_key())
        changes = sorted(changes, key=lambda c: c.sort_key())
        validate_records(
            self.context, records, changes, now=now, binding_created_at=binding.created_at
        )
        _atomic_write(self.changes_path, encode_jsonl(changes))  # first: see the module doc
        _atomic_write(self.path, encode_jsonl(records))


@contextlib.contextmanager
def joint_lock(store: JointStore, *, recorded_by: str, now: datetime) -> Iterator[LockInfo]:
    info = LockInfo(
        second_review_manifest_sha256=store.context.targeted.manifest.manifest_sha256,
        recorded_by=recorded_by,  # type: ignore[arg-type]
        pid=os.getpid(),
        started_at=now,
    )
    store.directory.mkdir(parents=True, exist_ok=True)
    try:
        with open(store.lock_path, "x", encoding="utf-8", newline="\n") as handle:
            handle.write(json.dumps(info.model_dump(mode="json"), sort_keys=True) + "\n")
            handle.flush()
            os.fsync(handle.fileno())
    except FileExistsError:
        raise JointResolutionError(
            f"another joint-resolution session holds {store.lock_path.name}. If none is running "
            "(for example after a hard kill), confirm `validate` passes, then delete the lock "
            "file by hand and rerun. It is never removed automatically."
        ) from None
    try:
        yield info
    finally:
        store.lock_path.unlink(missing_ok=True)


