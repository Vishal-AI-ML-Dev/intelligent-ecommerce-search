def _judgement_lines(title: str, j: Judgement) -> list[str]:
    return [
        title,
        f"  label:              {j.label.value}",
        f"  relation:           {j.relation.value}",
        f"  confidence:         {j.confidence.value}",
        f"  rationale:          {j.rationale or '(none)'}",
        f"  needs adjudication: {'yes' if j.needs_adjudication else 'no'}",
        f"  catalog issue:      {'yes' if j.catalog_issue else 'no'}",
    ]


def render_pair(context: JointContext, item: JointResolutionItem, number: int, total: int) -> str:
    targeted = context.targeted
    sealed = targeted.sealed
    pair = (item.query_id, item.product_id)
    query = sealed.queries[item.query_id]
    lines = [f"--- joint pair {number} of {total}: {item.query_id} / {item.product_id} ---"]
    lines.append(f"query {query.query_id}: {query.text}")
    lines += [f"  interpretation: {text}" for text in query.interpretations]
    own = sorted(
        (c for c in sealed.constraints if c.query_id == item.query_id), key=lambda c: c.sort_key()
    )
    lines += [
        f"  {c.hardness.value} gold constraint: {c.field.value} {c.operator.value} "
        f"{canonical_gold_value(c.value)}"
        for c in own
    ]
    if not own:
        lines.append("  (no gold constraints recorded for this query)")
    intents = sorted(
        (i for i in sealed.intents if i.query_id == item.query_id), key=lambda i: i.sort_key()
    )
    lines += [f"  soft {i.kind.value} intent: {i.value}" for i in intents]
    lines += [f"  hard constraints overall: {sealed.eligibility[pair].hard_overall.value}", ""]
    lines.append(render_card(sealed.catalog.products[item.product_id]))
    lines += ["", "routed for joint resolution: " + ", ".join(r.value for r in item.reasons)]
    queued = next((i for i in targeted.queue if (i.query_id, i.product_id) == pair), None)
    if queued is not None:
        lines.append(
            "also in ann-1's targeted queue (this joint record settles it): "
            + ", ".join(r.value for r in queued.review_reasons)
        )
    if JointReason.SECOND_REVIEW_CATALOG_ISSUE in item.reasons:
        lines.append("catalog issue: note it in the joint rationale; catalog data is never edited")
    lines += _judgement_lines("sealed ann-1 primary judgement:", targeted.primaries[pair])
    lines += _judgement_lines("sealed ann-2 second-review judgement:", context.second_reviews[pair])
    return "\n".join(lines)


def summary(record: ConsensusAdjudication, change_reason: str | None) -> str:
    outcome = (
        f"CHANGED: {record.primary_label.value} -> {record.label.value}"
        if record.changes_label
        else f"primary label kept: {record.label.value}"
    )
    return "\n".join(
        [
            "summary of this joint resolution (nothing is saved yet):",
            "  resolves:            " + ", ".join(r.value for r in record.reasons),
            f"  sealed labels:       ann-1 {record.primary_label.value} / "
            f"ann-2 {record.second_review_label.value}",
            f"  agreed label:        {outcome}",
            f"  agreed relation:     {record.relation.value}",
            f"  joint rationale:     {record.rationale}",
            f"  label change reason: {change_reason or '(none: the primary label is kept)'}",
            "  participants:        " + " and ".join(record.participants),
        ]
    )


def ask_joint(
    context: JointContext,
    item: JointResolutionItem,
    ask: Ask,
    say: Say,
    now: Now,
    *,
    recorded_by: str,
) -> tuple[ConsensusAdjudication, LabelChange | None] | None:
    """One joint resolution, step by step, or None when the pair is skipped (unresolved).
    Nothing is prefilled; a record needs both participants' typed confirmation and a `y`."""
    targeted = context.targeted
    pair = (item.query_id, item.product_id)
    primary = targeted.primaries[pair]
    second = context.second_reviews[pair]
    status = targeted.sealed.eligibility[pair].hard_overall
    while True:
        action = _choose(
            ask,
            say,
            "0 have both annotators reached a joint resolution? [r]ecord it / [s]kip, leave it "
            "unresolved / [q]uit: ",
            ACTION_KEYS,
        )
        if action == "skip":
            say("skipped: no record; this pair stays unresolved and blocks the label freeze")
            return None
        label = _choose(
            ask, say, "1 agreed label [r]elevant / [b]orderline / [n]ot_relevant: ", LABEL_KEYS
        )
        if label is Label.RELEVANT and status is OverallStatus.VIOLATED:
            say(HARD_VIOLATION_MESSAGE)
            continue
        keys = _relation_keys(label)
        menu = " / ".join(f"[{k}] {r.value}" for k, r in keys.items())
        relation = _choose(ask, say, f"2 agreed relation {menu}: ", keys)
        rationale = _free_text(ask, say, "3 joint rationale (required): ", True)
        changes_label = label is not primary.label
        change_reason = (
            _free_text(
                ask,
                say,
                f"4 label change reason (required: {primary.label.value} -> {label.value}): ",
                True,
            )
            if changes_label
            else None
        )
        decided_at = now()
        try:
            record = ConsensusAdjudication(
                query_id=item.query_id,
                product_id=item.product_id,
                reasons=item.reasons,
                primary_label=primary.label,
                second_review_label=second.label,
                label=label,
                relation=relation,
                rationale=rationale,  # type: ignore[arg-type]
                participants=PARTICIPANTS,  # type: ignore[arg-type]
                decided_at=decided_at,
                rubric_version=primary.rubric_version,
                changes_label=changes_label,
            )
            change = (
                LabelChange(
                    query_id=item.query_id,
                    product_id=item.product_id,
                    kind=LabelChangeKind.CONSENSUS,
                    previous_label=primary.label,
                    new_label=label,
                    reason=change_reason,  # type: ignore[arg-type]
                    changed_by=recorded_by,
                    changed_at=decided_at,
                    from_golden_version=targeted.golden_version,
                    to_golden_version=targeted.golden_version,
                )
                if changes_label
                else None
            )
        except ValueError as exc:
            say(f"not saved: {exc}")
            continue
        say(summary(record, change_reason))
        confirmed = True
        for handle in PARTICIPANTS:
            typed = _ask(
                ask, f"5 {handle}: type {handle} to confirm you agree, anything else declines: "
            )
            if typed != handle:
                confirmed = False
                break
        if not confirmed:
            say("not confirmed by both participants; nothing was saved for this pair")
            continue
        answer = _ask(ask, "6 save this joint record? type y to save, anything else discards: ")
        if answer.lower() == "y":
            return record, change
        say("discarded; nothing was saved for this pair")


def annotate(
    context: JointContext,
    store: JointStore,
    *,
    recorded_by: str,
    ask: Ask = input,
    say: Say = print,
    now: Now = lambda: datetime.now(UTC),
) -> int:
    """Record joint resolutions for the unresolved routed pairs until done or stopped."""
    if recorded_by not in PARTICIPANTS:
        raise JointResolutionError(f"refused: --recorded-by must be one of {PARTICIPANTS!r}")
    with joint_lock(store, recorded_by=recorded_by, now=now()):
        store.initialize(now=now())
        removed = store.repair_interrupted_save(now=now())
        if removed:
            say(
                f"removed {removed} label change(s) whose joint record was never saved (an "
                "interrupted save); those pairs are asked again"
            )
        records, changes = store.load(now=now())
        done = {(r.query_id, r.product_id) for r in records}
        todo = [i for i in context.items if (i.query_id, i.product_id) not in done]
        total = len(context.items)
        say(f"{len(done)} of {total} joint-resolution pairs recorded; {len(todo)} unresolved")
        saved = skipped = 0
        for offset, item in enumerate(todo):
            say("")
            say(render_pair(context, item, len(done) + offset + 1, total))
            try:
                result = ask_joint(context, item, ask, say, now, recorded_by=recorded_by)
            except Stop:
                say(f"stopped; {saved} joint record(s) saved this session")
                return saved
            if result is None:
                skipped += 1
                continue
            record, change = result
            records.append(record)
            if change is not None:
                changes.append(change)
            store.save(records, changes, now=now())
            saved += 1
            say("saved")
        unresolved = total - len(done) - saved
        say(
            f"{len(done) + saved} of {total} joint-resolution pairs recorded; {unresolved} "
            "unresolved (they block the label freeze)"
        )
        return saved


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="python -m evals.annotation.joint_resolution")
    parser.add_argument("--golden-dir", type=Path, default=build_pool.DEFAULT_GOLDEN_DIR)
    parser.add_argument("--work-root", type=Path, default=WORK_ROOT)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("status", help="progress counts only")
    run = commands.add_parser("annotate", help="record joint resolutions, both annotators present")
    run.add_argument(
        "--recorded-by",
        required=True,
        help="the participant recording this session (ann-1 or ann-2); recorded as changed_by",
    )
    commands.add_parser("validate", help="re-check the working files; writes nothing")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        context = load_joint(args.golden_dir)
        store = JointStore(context, args.work_root)
        if args.command == "annotate":
            annotate(context, store, recorded_by=args.recorded_by)
            return 0
        records, changes = store.load(now=datetime.now(UTC))
        total = len(context.items)
        if args.command == "status":
            print(f"second_review_sealed {context.targeted.manifest.manifest_sha256}")
            print(
                f"{len(records)} of {total} joint-resolution pairs recorded; "
                f"{total - len(records)} unresolved (they block the label freeze)"
            )
            print(f"{len(changes)} consensus label change record(s)")
            if store.lock_path.exists():
                print(
                    "a joint-resolution lock is present (a session is running or was hard-killed)"
                )
        else:
            print(
                f"working files valid: {len(records)} joint record(s), "
                f"{len(changes)} consensus label change(s)"
            )
    except ContractError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
